// Character registry — the single place that knows which playable characters exist (Bible/Game Mode, Momo integration prep).
//  * 'builtin' characters are the existing ones (rabbit default, lemon, pill); they are NOT changed or replaced.
//  * 'gltf' characters are external rigged GLBs. Momo (stylised upright-bipedal red panda) is registered here; the definitive model is supplied later at
//    public/models/momo.glb. Until that file exists the character is reported unavailable and the game safely falls back to the rabbit.
//  * A technical placeholder (public/models/_TECHNICAL_PLACEHOLDER_biped.glb, generated by assets/blender/make_character_placeholder.py) validates the
//    loader / mixer / state machine. It is dev-only (?dev=1) and is NOT a Momo substitute.
// Selection order: ?model=<id> (session) > localStorage 'ww.character' (persistent) > 'rabbit'.
const BASE = (typeof import.meta !== 'undefined' && import.meta.env && import.meta.env.BASE_URL) || '/'
const Q = typeof window !== 'undefined' ? new URLSearchParams(window.location.search) : new URLSearchParams()
const safe = (f, d) => { try { return f() } catch { return d } }

// Animation state -> candidate clip names in the GLB (first match wins, case-insensitive; also tries "<name>_loop" style suffixes).
export const CLIP_ALIASES = {
  idle: ['idle', 'idle_loop', 'stand', 'breathing'],
  walk: ['walk', 'walk_loop', 'walking'],
  run: ['run', 'run_loop', 'running', 'sprint'],
  jump: ['jump', 'jump_loop', 'hop'],
  sit: ['sit', 'sit_loop', 'sitting', 'sit_idle'],
  sleep: ['sleep', 'sleep_loop', 'sleeping', 'nap'],
  wave: ['wave', 'greet', 'hello'],
  cheer: ['cheer', 'celebrate', 'happy', 'victory'],
  emote_happy: ['emote_happy', 'happy', 'joy'], emote_sad: ['emote_sad', 'sad'], emote_surprised: ['emote_surprised', 'surprised', 'surprise'], emote_love: ['emote_love', 'love', 'heart'],
}
// When a clip is missing, fall back along this chain so a partial animation set still plays sensibly.
export const CLIP_FALLBACK = { run: 'walk', walk: 'idle', jump: 'idle', sit: 'idle', sleep: 'sit', wave: 'idle', cheer: 'wave', emote_happy: 'cheer', emote_sad: 'idle', emote_surprised: 'idle', emote_love: 'wave' }
export const ONE_SHOT = new Set(['jump', 'wave', 'cheer', 'emote_happy', 'emote_sad', 'emote_surprised', 'emote_love'])   // play once, then return to locomotion
export const HOLD = new Set(['sit', 'sleep'])                                                                         // loop until cancelled

export const CHARACTERS = [
  { id: 'rabbit', label: 'Rabbit', kind: 'builtin', note: 'default playable pet (procedural run cycle)' },
  { id: 'lemon', label: 'Lemon', kind: 'builtin' },
  { id: 'pill', label: 'Pill', kind: 'builtin' },
  { id: 'momo', label: 'Momo (red panda)', kind: 'gltf', url: `${BASE}models/momo.glb`, height: 1.1, faceFix: 0, locomotion: 'upright-biped', clips: CLIP_ALIASES },
  { id: 'tech_placeholder', label: 'Technical placeholder (dev)', kind: 'gltf', url: `${BASE}models/_TECHNICAL_PLACEHOLDER_biped.glb`, height: 1.1, faceFix: 0, devOnly: true, placeholder: true, clips: CLIP_ALIASES },
]
export const byId = (id) => CHARACTERS.find((c) => c.id === id)
export const isDev = () => Q.get('dev') === '1'

// availability of gltf files, probed once (HEAD). Builtins are always available.
const probed = {}
export async function probeAvailability() {
  await Promise.all(CHARACTERS.filter((c) => c.kind === 'gltf').map(async (c) => {
    if (c.id in probed) return
    try { const r = await fetch(c.url, { method: 'HEAD' }); probed[c.id] = r.ok && !/text\/html/.test(r.headers.get('content-type') || '') } catch { probed[c.id] = false }
  }))
  return { ...probed }
}
export const isAvailable = (c) => c.kind === 'builtin' || probed[c.id] === true
export const listSelectable = () => CHARACTERS.filter((c) => (!c.devOnly || isDev()) && isAvailable(c))

export function requestedId() {
  const q = Q.get('model'); if (q && byId(q)) return q
  const s = safe(() => localStorage.getItem('ww.character'), null); if (s && byId(s)) return s
  return 'rabbit'
}
// persistent choice; takes effect on next load (the player rig is built once per session) — the picker reloads for you
export function persistSelection(id) { if (byId(id)) safe(() => localStorage.setItem('ww.character', id)) }
export function switchCharacter(id) {
  persistSelection(id)
  const u = new URL(window.location.href); u.searchParams.delete('model'); window.location.href = u.toString()
}
