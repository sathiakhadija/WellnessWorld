// Settings-menu evidence/test: closed bar, open panel, click weather + time buttons, Escape closes, keyboard shortcut still works.
const { chromium } = require('playwright')
;(async () => {
  const b = await chromium.launch({ args: ['--use-gl=swiftshader','--enable-webgl','--ignore-gpu-blocklist','--use-angle=swiftshader'] })
  const p = await b.newPage({ viewport: { width: 1100, height: 620 } }); const errs=[]; p.on('pageerror',e=>errs.push(e.message))
  const out=process.argv[2]
  const click=(sel)=>p.evaluate((q)=>{const e=q.startsWith('text=')?[...document.querySelectorAll('button')].find(x=>x.textContent.includes(q.slice(5))):document.querySelector(q); if(!e) throw new Error('missing '+q); e.click()},sel)
  await p.goto('http://localhost:4176/?weather=sunny',{waitUntil:'load'})
  await p.waitForFunction(()=>window.__ww&&window.__street,null,{timeout:300000}); await p.waitForTimeout(4000)
  await p.evaluate(()=>window.__ww.setFree(1.2,1.6,-3.2,3.1416,0,60)); await p.waitForTimeout(6000)
  console.log('panel hidden at start', await p.locator('#wwx-settings').isHidden())
  await p.screenshot({path:out+'/settings_closed.png'})
  await click('text=Settings'); await p.waitForTimeout(2000)
  console.log('panel visible after click', await p.locator('#wwx-settings').isVisible())
  await p.screenshot({path:out+'/settings_open.png'})
  await click('button[aria-label="Heavy rain"]').catch(()=>console.log('no Rain button label'))
  console.log('weather kind', await p.evaluate(()=>window.__weather.store.get().kind))
  await click('button[aria-label="Cosy Night"]').catch(()=>console.log('no night label'))
  console.log('preset', await p.evaluate(()=>window.__atmo.get().preset))
  await p.waitForTimeout(6000); await p.screenshot({path:out+'/settings_open_rain_night.png'})
  await p.keyboard.press('Escape'); await p.waitForTimeout(800)
  console.log('panel hidden after Escape', await p.locator('#wwx-settings').isHidden())
  await p.keyboard.press(']'); await p.waitForTimeout(800); console.log('shortcut ] preset', await p.evaluate(()=>window.__atmo.get().preset))
  console.log('errors',JSON.stringify(errs.slice(0,3))); await b.close()
})().catch(e=>{console.error(e);process.exit(2)})
